/** Generate a unit test for the service (mocks the repository). */
export function generateServiceUnitTest(meta: TableMetadata): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  return `/**
 * tests/unit/${tableName}.service.test.ts
 * ---------------------------------------------------------------
 * Unit tests for ${className}Service — uses a MOCK repository so
 * no database is required. Validates business logic, NOT persistence.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Run:  npm run test:unit -- ${tableName}.service
 */
import { ${className}Service } from '../../src/application/services/${tableName}/${tableName}.service';

// Mock the database module BEFORE importing the service. We build the
// mock repo inside the factory so jest.mock's hoisting doesn't trip on
// a top-level const reference.
jest.mock('../../src/infrastructure/database/database', () => {
  const mockRepo = {
    find: jest.fn().mockResolvedValue([]),
    findOne: jest.fn().mockResolvedValue(null),
    create: jest.fn((x: unknown) => x),
    save: jest.fn((x: unknown) => Promise.resolve(x)),
    merge: jest.fn((a: unknown, b: unknown) => ({ ...(a as object), ...(b as object) })),
    delete: jest.fn().mockResolvedValue({ affected: 0 }),
    count: jest.fn().mockResolvedValue(0),
    softDelete: jest.fn().mockResolvedValue({ affected: 0 }),
    createQueryBuilder: jest.fn(() => ({
      where: jest.fn().mockReturnThis(),
      orWhere: jest.fn().mockReturnThis(),
      skip: jest.fn().mockReturnThis(),
      take: jest.fn().mockReturnThis(),
      getMany: jest.fn().mockResolvedValue([]),
    })),
  };
  return {
    AppDataSource: {
      isInitialized: true,
      getRepository: jest.fn(() => mockRepo),
      transaction: jest.fn((fn: (m: unknown) => unknown) => fn({})),
    },
    // Expose for assertions / overrides in tests.
    __mockRepo: mockRepo,
  };
});

// eslint-disable-next-line @typescript-eslint/no-var-requires
const { __mockRepo } = require('../../src/infrastructure/database/database') as {
  __mockRepo: {
    find: jest.Mock;
    findOne: jest.Mock;
    create: jest.Mock;
    save: jest.Mock;
    merge: jest.Mock;
    delete: jest.Mock;
    count: jest.Mock;
    softDelete: jest.Mock;
  };
};

describe('${className}Service (unit)', () => {
  let service: ${className}Service;

  beforeEach(() => {
    // Clear call history (mockClear) WITHOUT resetting implementations
    // (which would also clear AppDataSource.getRepository's return value).
    Object.values(__mockRepo).forEach((m) => m.mockClear());
    // Re-establish default resolved values.
    __mockRepo.find.mockResolvedValue([]);
    __mockRepo.findOne.mockResolvedValue(null);
    __mockRepo.delete.mockResolvedValue({ affected: 0 });
    __mockRepo.count.mockResolvedValue(0);
    __mockRepo.save.mockImplementation((x: unknown) => Promise.resolve(x));
    service = new ${className}Service();
  });

  it('instantiates without throwing', () => {
    expect(service).toBeInstanceOf(${className}Service);
  });

  it('list() returns an array', async () => {
    const result = await service.list(0, 10);
    expect(Array.isArray(result)).toBe(true);
    expect(__mockRepo.find).toHaveBeenCalled();
  });

  it('count() returns a number', async () => {
    const result = await service.count();
    expect(typeof result).toBe('number');
    expect(__mockRepo.count).toHaveBeenCalled();
  });

  it('delete() returns false when the row does not exist', async () => {
    // Default mock returns null for findOne, so delete should be a no-op.
    const result = await service.delete('nonexistent-id');
    expect(result).toBe(false);
  });

  it('getById() returns null when not found', async () => {
    const result = await service.getById('nonexistent-id');
    expect(result).toBeNull();
  });
});
`;
}

/** Generate an integration test for the repository (uses a real DB). */
export function generateRepositoryIntegrationTest(meta: TableMetadata): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  return `/**
 * tests/integration/${tableName}.repository.test.ts
 * ---------------------------------------------------------------
 * Integration tests for ${className}Repository — exercises a REAL
 * PostgreSQL database. Set DATABASE_URL to a throwaway test DB.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Run:  DATABASE_URL=... npm run test:integration -- ${tableName}.repository
 *
 * These tests are SKIPPED if DATABASE_URL points at the production
 * host — guard against accidentally running them against prod.
 */
import { initDatabase, closeDatabase, AppDataSource } from '../../src/infrastructure/database/database';
import { ${className}Repository } from '../../src/infrastructure/repositories/${tableName}/${tableName}.repository';
import { ${className} } from '../../src/domain/${tableName}/${tableName}.entity';
import { makeId } from '../helpers/factory';

const DATABASE_URL = process.env.DATABASE_URL ?? '';
const RUN_DB_TESTS = process.env.RUN_DB_TESTS === 'true' || process.env.CI === 'true';
const describeOrSkip = RUN_DB_TESTS ? describe : describe.skip;

describeOrSkip('${className}Repository (integration)', () => {
  let repo: ${className}Repository;

  beforeAll(async () => {
    await initDatabase();
    repo = new ${className}Repository();
  });

  afterAll(async () => {
    await closeDatabase();
  });

  afterEach(async () => {
    // Clean up rows created during each test.
    if (AppDataSource.isInitialized) {
      await AppDataSource.getRepository(${className}).delete({});
    }
  });

  it('findById returns null for unknown id', async () => {
    const result = await repo.findById(makeId());
    expect(result).toBeNull();
  });

  it('findMany returns an array', async () => {
    const result = await repo.findMany({ skip: 0, take: 10 });
    expect(Array.isArray(result)).toBe(true);
  });

  it('count returns a non-negative number', async () => {
    const result = await repo.count();
    expect(result).toBeGreaterThanOrEqual(0);
  });

  it('exists returns false for unknown row', async () => {
    const result = await repo.exists({ id: makeId() } as never);
    expect(result).toBe(false);
  });
});
`;
}

/** Generate an e2e test for the controller (uses supertest). */
export function generateApiE2eTest(meta: TableMetadata): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  return `/**
 * tests/e2e/${tableName}.api.test.ts
 * ---------------------------------------------------------------
 * End-to-end tests for the /api/v1/${tableName} endpoints via the
 * real Express app (no DB mocking). Requires a running PostgreSQL.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Run:  npm run test:e2e -- ${tableName}.api
 */
import request, { Response } from 'supertest';
import { Application } from 'express';
import { createApp } from '../../src/app';
import { initDatabase, closeDatabase } from '../../src/infrastructure/database/database';
import { makeJwt } from '../helpers/factory';

const DATABASE_URL = process.env.DATABASE_URL ?? '';
const RUN_DB_TESTS = process.env.RUN_DB_TESTS === 'true' || process.env.CI === 'true';
const describeOrSkip = RUN_DB_TESTS ? describe : describe.skip;

describeOrSkip('${className} API (e2e)', () => {
  let app: Application;

  beforeAll(async () => {
    await initDatabase();
    app = createApp();
  });

  afterAll(async () => {
    await closeDatabase();
  });

  it('GET /api/v1/${tableName} without auth returns 401', async () => {
    const res: Response = await request(app).get('/api/v1/${tableName}');
    expect(res.status).toBe(401);
  });

  it('GET /api/v1/${tableName} with auth returns 200', async () => {
    const token = makeJwt({ roles: ['admin'] });
    const res: Response = await request(app)
      .get('/api/v1/${tableName}')
      .set('Authorization', \`Bearer \${token}\`);
    expect([200, 500]).toContain(res.status); // 500 = DB not available
  });

  it('GET /api/v1/${tableName}/nonexistent returns 404 or 400', async () => {
    const token = makeJwt({ roles: ['admin'] });
    const res: Response = await request(app)
      .get('/api/v1/${tableName}/nonexistent-id')
      .set('Authorization', \`Bearer \${token}\`);
    expect([404, 400, 500]).toContain(res.status);
  });

  it('POST /api/v1/${tableName} with empty body returns 400', async () => {
    const token = makeJwt({ roles: ['admin'] });
    const res: Response = await request(app)
      .post('/api/v1/${tableName}')
      .set('Authorization', \`Bearer \${token}\`)
      .send({});
    expect([400, 500]).toContain(res.status);
  });

  it('DELETE /api/v1/${tableName}/nonexistent returns 404', async () => {
    const token = makeJwt({ roles: ['admin'] });
    const res: Response = await request(app)
      .delete('/api/v1/${tableName}/nonexistent-id')
      .set('Authorization', \`Bearer \${token}\`);
    expect([404, 500]).toContain(res.status);
  });
});
`;
}

