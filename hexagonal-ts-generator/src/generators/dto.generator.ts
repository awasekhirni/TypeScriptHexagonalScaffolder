import { ColumnInfo, TableAnalysis, TableMetadata } from '../types';
import { toPascalCase } from '../utils/naming';

/** Map a column to a TypeScript type literal (used in the DTO). */
function columnToTsType(col: ColumnInfo): string {
  const t = col.dataType.toLowerCase();
  const udt = col.udtName.toLowerCase();
  if (udt.startsWith('_')) return `${columnToTsType({ ...col, udtName: udt.slice(1), dataType: udt.slice(1) })}[]`;
  switch (t) {
    case 'uuid':
    case 'character varying':
    case 'character':
    case 'text':
      return 'string';
    case 'integer':
    case 'smallint':
    case 'bigint':
    case 'numeric':
    case 'decimal':
    case 'real':
    case 'double precision':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'date':
    case 'timestamp without time zone':
    case 'timestamp with time zone':
    case 'time without time zone':
      return 'Date';
    case 'json':
    case 'jsonb':
      return 'Record<string, unknown>';
    case 'bytea':
      return 'Buffer';
    default:
      return 'string';
  }
}

/**
 * Build the field list for the DTO files. Excludes server-managed
 * columns (id, created_at, updated_at, is_deleted, deleted_at) from
 * Create / Update DTOs.
 */
function writableColumns(meta: TableMetadata): ColumnInfo[] {
  const skip = new Set(['id', 'created_at', 'updated_at', 'modified_at', 'is_deleted', 'deleted_at', 'deleted']);
  return meta.columns.filter((c) => !skip.has(c.columnName.toLowerCase()) && !c.isPrimaryKey);
}

function readableColumns(meta: TableMetadata): ColumnInfo[] {
  return meta.columns;
}

/** Emit the DTO file (Create / Update / Response). */
export function generateDto(meta: TableMetadata, _analysis: TableAnalysis): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  const writes = writableColumns(meta);
  const reads = readableColumns(meta);

  // Create DTO fields
  const createFields = writes.map((c) => {
    const ts = columnToTsType(c);
    const decorators: string[] = [];
    if (ts === 'string') decorators.push(`  @IsString()`);
    if (ts === 'number') decorators.push(`  @IsNumber()`);
    if (ts === 'boolean') decorators.push(`  @IsBoolean()`);
    if (ts === 'Date') decorators.push(`  @IsDate()`);
    if (ts.startsWith('Record<string, unknown>')) decorators.push(`  @IsObject()`);
    if (!c.isNullable && !c.columnDefault) decorators.push(`  @IsNotEmpty()`);
    else decorators.push(`  @IsOptional()`);
    return `${decorators.join('\n')}\n  ${c.columnName}${c.isNullable ? '?' : '!'}: ${ts};`;
  }).join('\n\n');

  // Update DTO fields — every field optional
  const updateFields = writes.map((c) => {
    const ts = columnToTsType(c);
    const decorators: string[] = ['  @IsOptional()'];
    if (ts === 'string') decorators.push(`  @IsString()`);
    if (ts === 'number') decorators.push(`  @IsNumber()`);
    if (ts === 'boolean') decorators.push(`  @IsBoolean()`);
    if (ts === 'Date') decorators.push(`  @IsDate()`);
    if (ts.startsWith('Record<string, unknown>')) decorators.push(`  @IsObject()`);
    return `${decorators.join('\n')}\n  ${c.columnName}?: ${ts};`;
  }).join('\n\n');

  // Response DTO fields — every readable column
  const responseFields = reads.map((c) => {
    const ts = columnToTsType(c);
    return `  ${c.columnName}${c.isNullable ? '?' : '!'}: ${ts};`;
  }).join('\n');

  return `/**
 * src/api/dtos/${tableName}.dto.ts
 * ---------------------------------------------------------------
 * Request / response DTOs for ${className}.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * The Create / Update DTOs use class-validator decorators so the
 * controller can run a single \`validate()\` call to enforce the rules.
 *
 * Copyright 2025 β ORI Inc. Canada. All Rights Reserved.
 */
import {
  IsString, IsNumber, IsBoolean, IsDate, IsOptional,
  IsNotEmpty, IsObject,
} from 'class-validator';
import { Type } from 'class-transformer';

export class ${className}CreateDTO {
${createFields || '  // (no writable columns)'}
}

export class ${className}UpdateDTO {
${updateFields || '  // (no writable columns)'}
}

export class ${className}ResponseDTO {
${responseFields || '  // (no columns)'}
}

/** Convenience type alias used by the mapper. */
export type T${className}Create = ${className}CreateDTO;
export type T${className}Update = ${className}UpdateDTO;
export type T${className}Response = ${className}ResponseDTO;
`;
}

/**
 * Emit the validation wrapper that turns a raw payload into a typed,
 * validated DTO. The Python original emitted Pydantic validators; we
 * use class-validator + class-transformer.
 */
export function generateValidation(meta: TableMetadata, _analysis: TableAnalysis): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;

  return `/**
 * src/api/validations/${tableName}.validation.ts
 * ---------------------------------------------------------------
 * Validation helpers for ${className} request payloads.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Copyright 2025 β ORI Inc. Canada. All Rights Reserved.
 */
import { plainToInstance } from 'class-transformer';
import { validateOrReject, ValidationError } from 'class-validator';
import {
  ${className}CreateDTO,
  ${className}UpdateDTO,
} from '../dtos/${tableName}.dto';
import { badRequest } from '../../shared/utils/http-error';

/**
 * Validate a raw object as a ${className}CreateDTO.
 * Throws an HttpError(400) with the failing rules attached as details.
 */
export async function validate${className}Create(payload: unknown): Promise<${className}CreateDTO> {
  const dto = plainToInstance(${className}CreateDTO, payload, { excludeExtraneousValues: false });
  try {
    await validateOrReject(dto, { whitelist: true, forbidNonWhitelisted: false });
    return dto;
  } catch (err) {
    throw badRequest('Validation failed', formatErrors(err as ValidationError[]));
  }
}

/**
 * Validate a raw object as a ${className}UpdateDTO.
 * All fields are optional, but if any are present they must pass.
 */
export async function validate${className}Update(payload: unknown): Promise<${className}UpdateDTO> {
  const dto = plainToInstance(${className}UpdateDTO, payload, { excludeExtraneousValues: false });
  try {
    await validateOrReject(dto, { whitelist: true, forbidNonWhitelisted: false });
    return dto;
  } catch (err) {
    throw badRequest('Validation failed', formatErrors(err as ValidationError[]));
  }
}

function formatErrors(errors: ValidationError[]): Array<Record<string, unknown>> {
  return errors.map((e) => ({
    property: e.property,
    constraints: e.constraints,
  }));
}
`;
}
