import { TableAnalysis, TableMetadata } from '../types';
import { toPascalCase } from '../utils/naming';

/** Emit the service interface file contents for one table. */
export function generateServiceInterface(meta: TableMetadata, analysis: TableAnalysis): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  const interfaceName = `IAsync${className}Service`;

  const methods: string[] = [];

  methods.push(`  /** Get a ${className} by id. */
  getById(id: string | number): Promise<${className} | null>;`);

  methods.push(`  /** List ${className} rows with pagination. */
  list(skip?: number, take?: number): Promise<${className}[]>;`);

  methods.push(`  /** Create a ${className} from a partial payload. */
  create(data: DeepPartial<${className}>): Promise<${className}>;`);

  methods.push(`  /** Update a ${className} by id. */
  update(id: string | number, data: DeepPartial<${className}>): Promise<${className} | null>;`);

  methods.push(`  /** Delete a ${className} by id. */
  delete(id: string | number): Promise<boolean>;`);

  if (analysis.hasStatus) {
    methods.push(`  /** List ${className} rows by status. */
  listByStatus(status: string, skip?: number, take?: number): Promise<${className}[]>;`);
    methods.push(`  /** Change a ${className}'s status, optionally with a reason for the audit log. */
  changeStatus(id: string | number, newStatus: string, reason?: string): Promise<${className} | null>;`);
  }

  if (analysis.hasTimestamps) {
    methods.push(`  /** List ${className} rows created in the last N days. */
  listRecentlyCreated(days?: number, skip?: number, take?: number): Promise<${className}[]>;`);
    methods.push(`  /** List ${className} rows updated in the last N days. */
  listRecentlyUpdated(days?: number, skip?: number, take?: number): Promise<${className}[]>;`);
  }

  if (analysis.hasSoftDelete) {
    methods.push(`  /** Soft-delete a ${className}. */
  softDelete(id: string | number, reason?: string): Promise<boolean>;`);
    methods.push(`  /** Restore a previously soft-deleted ${className}. */
  restore(id: string | number): Promise<boolean>;`);
  }

  if (analysis.hasUserRelation) {
    methods.push(`  /** List every ${className} belonging to the given user. */
  listForUser(userId: string | number, skip?: number, take?: number): Promise<${className}[]>;`);
  }

  // Business-logic helpers
  methods.push(`  /** Free-text search across the named fields. */
  search(query: string, fields?: string[], skip?: number, take?: number): Promise<${className}[]>;`);
  methods.push(`  /** Aggregate stats for dashboards (total count + status counts). */
  getStats(): Promise<Record<string, unknown>>;`);
  methods.push(`  /** Export the table to a CSV string. */
  exportToCsv(filters?: Record<string, unknown>): Promise<string>;`);
  methods.push(`  /** Import rows from a CSV string. Returns the number of rows inserted. */
  importFromCsv(csvData: string): Promise<number>;`);

  return `/**
 * src/domain/${tableName}/${tableName}.service.interface.ts
 * ---------------------------------------------------------------
 * Domain-layer service contract for the "${tableName}" table.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Copyright 2025 β ORI Inc. Canada. All Rights Reserved.
 */
import { DeepPartial } from 'typeorm';
import { ${className} } from './${tableName}.entity';

/**
 * Async service interface for ${className}.
 *
 * Services encapsulate business rules and orchestrate repository calls.
 * They also publish lifecycle events to the Enterprise Bus so cross-
 * cutting concerns (audit, search, notifications) can subscribe without
 * coupling to the service directly.
 */
export interface ${interfaceName} {
${methods.join('\n\n')}
}
`;
}
