/** Generate the per-table CQRS index.ts (registers all handlers). */
export function generateCqrsIndex(meta: TableMetadata): string {
  const className = toPascalCase(meta.name);
  const tableName = meta.name;
  return `/**
 * src/application/cqrs/${tableName}/index.ts
 * ---------------------------------------------------------------
 * Registers every ${className} command/query handler with the buses.
 * Import this module ONCE at boot (from src/server.ts) to wire up.
 *
 * AUTO-GENERATED by hexagonal-ts-generator.
 *
 * Copyright 2025 β ORI Inc. Canada. All Rights Reserved.
 */
import { commandBus, queryBus } from '../../../shared/cqrs/cqrs';
import {
  Create${className}Command,
  Update${className}Command,
  Delete${className}Command,
} from './${tableName}.commands';
import {
  Get${className}ByIdQuery,
  List${className}Query,
  Count${className}Query,
} from './${tableName}.queries';
import {
  Create${className}CommandHandler,
  Update${className}CommandHandler,
  Delete${className}CommandHandler,
} from './${tableName}.command-handlers';
import {
  Get${className}ByIdQueryHandler,
  List${className}QueryHandler,
  Count${className}QueryHandler,
} from './${tableName}.query-handlers';
import { childLogger } from '../../../shared/utils/logger';

const log = childLogger({ component: 'cqrs-bootstrap', aggregate: '${tableName}' });

export function register${className}CqrsHandlers(): void {
  commandBus.register(Create${className}Command, new Create${className}CommandHandler());
  commandBus.register(Update${className}Command, new Update${className}CommandHandler());
  commandBus.register(Delete${className}Command, new Delete${className}CommandHandler());
  queryBus.register(Get${className}ByIdQuery, new Get${className}ByIdQueryHandler());
  queryBus.register(List${className}Query, new List${className}QueryHandler());
  queryBus.register(Count${className}Query, new Count${className}QueryHandler());
  log.info('CQRS handlers registered', { commands: 3, queries: 3 });
}
`;
}
