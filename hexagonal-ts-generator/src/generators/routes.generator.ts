import { TableMetadata } from '../types';
import { toPascalCase } from '../utils/naming';

/** Emit the routes aggregator. */
export function generateRoutesAggregator(metadata: TableMetadata[]): string {
  const imports = metadata
    .map((m) => `import { register${toPascalCase(m.name)}Routes } from './controllers/${m.name}.controller';`)
    .join('\n');

  const registrations = metadata
    .map((m) => `  register${toPascalCase(m.name)}Routes(router);`)
    .join('\n');

  return `/**
 * src/api/routes.ts
 * ---------------------------------------------------------------
 * Aggregates every per-table controller and mounts them onto a single
 * Express router.
 *
 * AUTO-GENERATED by hexagonal-ts-generator. Editing this file by hand
 * is fragile — re-run the generator after schema changes instead.
 *
 * Copyright 2025 β ORI Inc. Canada. All Rights Reserved.
 */
import { Express, Router } from 'express';
${imports}

/**
 * Mounts every per-table router under the given prefix (typically
 * "/api/v1"). Called once from app.ts.
 *
 * Each controller's own factory mounts itself onto the parent router at
 * "/<tableName>", so the final URL becomes "<prefix>/<tableName>" —
 * e.g. "/api/v1/users", "/api/v1/posts".
 */
export function registerRoutes(app: Express, prefix = '/api/v1'): void {
  const router = Router();
${registrations}
  app.use(prefix, router);
}
`;
}
